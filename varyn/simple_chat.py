"""Chat-first interface. No fabricated AI replies or hidden provider requests.

External inference requires a separately reviewed model quote, owner credentials,
a live-network checkbox and a second exact-prompt approval on EVERY request.
"""
from __future__ import annotations

from datetime import date
import hashlib
import os
import queue
import threading
import tkinter as tk
from tkinter import ttk

from varyn.gateway_chat import KEY_ENVS, SafeProviderHTTPError
from varyn.model_control_center import create_reviewed_offer, build_exact_preview
from varyn.model_registry import Offer, Registry, RegistryRejected
from varyn.providers import ProviderError
from varyn.safety import assert_no_obvious_secrets
from varyn.universal_gateway import UniversalGateway
from varyn.usage_budget import BudgetExceeded


_MODES = ("Offline demo (not AI)", "OpenRouter", "DeepSeek")
_PROVIDER = {"OpenRouter": "openrouter", "DeepSeek": "deepseek"}


class ChatSurface(ttk.Frame):
    """Owner-local, RAM-only single-turn chat, shown immediately at launch."""

    def __init__(self, parent, desktop):
        super().__init__(parent)
        self.desktop = desktop
        self._offers = {}
        self._busy = False
        self._closed = False
        self._queue = queue.Queue()
        self._after_id = None
        self._request = None
        default = "Offline demo (not AI)"
        for label, provider in _PROVIDER.items():
            if os.environ.get(KEY_ENVS[provider], "").strip():
                default = label
                break
        self.mode = tk.StringVar(master=self, value=default)
        self.allow_network = tk.BooleanVar(master=self, value=False)
        self.status = tk.StringVar(master=self, value=(
            "Provider key detected. Configure model in Settings before sending."
            if default != "Offline demo (not AI)" else
            "Offline demo: answers are simulated, not generated by AI."
        ))
        self._build()

    def _build(self):
        bg = "#111b2d"
        surface = "#162339"
        text = "#f4f7fc"
        muted = "#93a5c0"
        accent = "#7868fa"
        style = ttk.Style(self)
        style.configure("Varyn.Chat.TFrame", background=bg)
        style.configure("Varyn.Combo.TCombobox",
                        fieldbackground=surface, background=surface,
                        foreground=text, arrowcolor=text,
                        bordercolor="#283952", padding=7)
        style.map("Varyn.Combo.TCombobox",
                  fieldbackground=[("readonly", surface)],
                  foreground=[("readonly", text)])
        self.configure(style="Varyn.Chat.TFrame")
        head = tk.Frame(self, bg=bg)
        head.pack(fill="x", pady=(1, 19))
        tk.Label(head, text="AI Chat", bg=bg, fg=text,
                 font=("Segoe UI", 24, "bold")).pack(side="left")
        tk.Button(head, text="⚙  Model settings",
                  command=self.open_settings, relief="flat",
                  bg=surface, fg=text, activebackground="#2b3c59",
                  activeforeground=text, cursor="hand2", bd=0,
                  font=("Segoe UI", 10, "bold"), padx=16, pady=10).pack(
                      side="right")
        controls = tk.Frame(self, bg=bg)
        controls.pack(fill="x", pady=(0, 14))
        tk.Label(controls, text="MODEL", bg=bg, fg=muted,
                 font=("Segoe UI", 9, "bold")).pack(side="left", padx=(0, 11))
        self.model_box = ttk.Combobox(
            controls, state="readonly", textvariable=self.mode,
            values=_MODES, width=24, style="Varyn.Combo.TCombobox",
            font=("Segoe UI", 10),
        )
        self.model_box.pack(side="left")
        self.model_box.bind("<<ComboboxSelected>>", self._mode_changed)
        tk.Checkbutton(
            controls, text="Allow one network request",
            variable=self.allow_network,
            bg=bg, fg=muted, selectcolor=surface,
            activebackground=bg, activeforeground=text,
            font=("Segoe UI", 9),
        ).pack(side="right")
        notice = tk.Frame(self, bg=surface, padx=13, pady=10)
        notice.pack(fill="x", pady=(0, 15))
        tk.Label(notice, text="●", bg=surface, fg="#6ad5a4",
                 font=("Segoe UI", 10, "bold")).pack(side="left", padx=(0, 8))
        tk.Label(notice, textvariable=self.status, bg=surface, fg=muted,
                 font=("Segoe UI", 9), anchor="w",
                 justify="left", wraplength=520).pack(side="left", fill="x",
                                                        expand=True)
        # Separate empty-state panel is styled as a conversation rather
        # than a technical log with fields and long notices.
        conversation = tk.Frame(self, bg="#0e1626")
        conversation.pack(fill="both", expand=True)
        self.chat = tk.Text(
            conversation, height=14,
            bg="#0e1626", fg=text, insertbackground=text,
            font=("Segoe UI", 11), wrap="word",
            padx=23, pady=20, relief="flat", state="disabled",
            spacing1=4, spacing3=8, borderwidth=0,
            highlightthickness=0,
        )
        self.chat.pack(side="left", fill="both", expand=True)
        scrollbar = tk.Scrollbar(conversation, command=self.chat.yview,
                                 bg=surface, troughcolor="#0e1626",
                                 relief="flat", width=10)
        scrollbar.pack(side="right", fill="y")
        self.chat.configure(yscrollcommand=scrollbar.set)
        self._append("VARYN", "Welcome to your workspace. Write a message below. "
                     "Offline demo is only a simulation. To get a genuine "
                     "AI answer, choose a provider and configure its model "
                     "under Model settings.")
        composer = tk.Frame(self, bg=surface, highlightbackground="#30425e",
                            highlightthickness=1)
        composer.pack(fill="x", pady=(16, 9))
        self.input = tk.Text(
            composer, height=3, wrap="word",
            bg=surface, fg=text, insertbackground=text,
            selectbackground="#374a7d",
            font=("Segoe UI", 11), padx=14, pady=14, relief="flat",
            borderwidth=0, highlightthickness=0,
        )
        self.input.pack(side="left", fill="both", expand=True)
        self.send = tk.Button(
            composer, text="Send  ↗", command=self.send_message,
            bg=accent, fg="#ffffff", activebackground="#9488ff",
            activeforeground="#ffffff", font=("Segoe UI", 11, "bold"),
            relief="flat", bd=0, padx=19, pady=12, cursor="hand2",
        )
        self.send.pack(side="right", padx=10, pady=10)
        self.input.bind("<Control-Return>",
                        lambda event: (self.send_message(), "break")[1])
        tk.Label(
            self, text="Ctrl+Enter to send   •   One message per request   "
                       "•   Your data is not uploaded without approval",
            bg=bg, fg=muted, font=("Segoe UI", 9),
            anchor="w", justify="left",
        ).pack(fill="x", pady=(0, 2))

    def _append(self, who, message):
        self.chat.configure(state="normal")
        self.chat.insert("end", who + "\n", ("speaker",))
        self.chat.insert("end", message + "\n\n")
        self.chat.tag_configure("speaker", foreground="#91b6ff",
                                font=("Segoe UI", 10, "bold"))
        self.chat.see("end")
        self.chat.configure(state="disabled")

    def _mode_changed(self, _event=None):
        self.allow_network.set(False)
        if self.mode.get() == "Offline demo (not AI)":
            self.status.set("Offline simulation. No real AI or internet request.")
        else:
            provider = _PROVIDER[self.mode.get()]
            if not os.environ.get(KEY_ENVS[provider], "").strip():
                self.status.set("Provider key missing. Relaunch using the owner launcher "
                                "with -Provider " + provider + ".")
            elif provider not in self._offers:
                self.status.set("Open Model Settings to add your reviewed model ID and prices.")
            else:
                self.status.set("Ready for per-request approval. Provider may bill usage.")

    def open_settings(self):
        if self._closed or self._busy:
            return
        name = self.mode.get()
        if name not in _PROVIDER:
            self.status.set("Choose OpenRouter or DeepSeek before configuring a live model.")
            return
        provider = _PROVIDER[name]
        popup = tk.Toplevel(self)
        popup.title("VARYN | Model setup (one time per app session)")
        popup.geometry("510x360")
        popup.transient(self.winfo_toplevel())
        popup.grab_set()
        shell = ttk.Frame(popup, padding=16)
        shell.pack(fill="both", expand=True)
        ttk.Label(shell, text="Configure " + name, font=("Segoe UI", 13, "bold")).pack(anchor="w")
        ttk.Label(shell, text="Enter the actual model ID and independently check current "
                            "provider input/output prices. Nothing is sent yet.",
                  wraplength=465).pack(anchor="w", pady=(5, 8))
        model = tk.StringVar(master=popup)
        input_price = tk.StringVar(master=popup)
        output_price = tk.StringVar(master=popup)
        accepted = tk.BooleanVar(master=popup, value=False)
        for label, variable in (
            ("Exact model ID", model),
            ("Input USD per 1 million tokens", input_price),
            ("Output USD per 1 million tokens", output_price),
        ):
            ttk.Label(shell, text=label).pack(anchor="w", pady=(5, 0))
            ttk.Entry(shell, textvariable=variable).pack(fill="x")
        ttk.Checkbutton(shell, variable=accepted, text=(
            "I checked BOTH actual prices and the selected provider/model route."
        )).pack(anchor="w", pady=(10, 4))
        feedback = tk.StringVar(master=popup, value="")
        ttk.Label(shell, textvariable=feedback).pack(anchor="w")
        def save():
            if not accepted.get():
                feedback.set("Review and confirm both prices before saving.")
                return
            try:
                offer = create_reviewed_offer(
                    provider=provider, model=model.get().strip(),
                    input_usd=input_price.get().strip(),
                    output_usd=output_price.get().strip(),
                    date_text=date.today().isoformat(),
                    reviewed=True, fixed=True,
                )
                Registry([offer])
            except (ValueError, RegistryRejected):
                feedback.set("Invalid model or price. No network action performed.")
                return
            self._offers[provider] = offer
            self.status.set("Model configured for " + provider +
                            " (RAM only). Approve each real request separately.")
            popup.destroy()
        ttk.Button(shell, text="Save reviewed model", command=save).pack(
            anchor="e", pady=(12, 0))

    def send_message(self):
        if self._busy or self._closed:
            return
        content = self.input.get("1.0", "end-1c")
        if not content.strip() or len(content) > 4000:
            self.status.set("Enter a question of 1 to 4,000 characters.")
            return
        if any(ord(c) < 32 and c not in "\r\n\t" for c in content):
            self.status.set("Invalid control character in question.")
            return
        try:
            assert_no_obvious_secrets(content)
        except (ValueError, Exception) as exc:
            # No unsafe content echoed in UI errors.
            self.status.set("Question rejected by local safety check. Remove secrets.")
            return
        name = self.mode.get()
        if name == "Offline demo (not AI)":
            # Do not fabricate a plausible model answer.
            self._append("You", content)
            self._append("Offline demo", "SIMULATION ONLY: no AI model was called. "
                         "Select a live provider for a real answer.")
            self.input.delete("1.0", "end")
            self.status.set("Demo complete. No network call, no provider billing.")
            return
        provider = _PROVIDER.get(name)
        if provider is None:
            self.status.set("Select a supported provider.")
            return
        offer = self._offers.get(provider)
        if offer is None:
            self.status.set("Set up an exact model and reviewed prices first (Model Settings).")
            self.open_settings()
            return
        if not os.environ.get(KEY_ENVS[provider], "").strip():
            self.status.set("No " + provider + " API key. Relaunch with -Provider " + provider + ".")
            return
        if not self.desktop._universal_model_live_capability or not self.allow_network.get():
            self.status.set("Check 'Allow ONE internet request' before sending.")
            return
        input_estimate = 256
        output_limit = 256
        try:
            registry = Registry([offer])
            estimate = registry.choose(
                input_estimate=input_estimate,
                output_limit=output_limit,
                ceiling_micro_usd=1000000000,
                today=date.today(),
            )[1]
            exact = build_exact_preview(offer, content, input_estimate, output_limit,
                                        estimate)
            digest = hashlib.sha256(exact.encode("utf-8")).hexdigest()
            approved = self.desktop._review_scrollable_manual_text(
                title="VARYN | Review outgoing AI request",
                heading="One approved request to " + provider + " / " + offer.model,
                digest=digest, content=exact,
                warning="Your question leaves this PC; provider may retain it and "
                        "charge money. This estimate is NOT a billing limit. "
                        "No file/history upload, no retries or automatic fallbacks.",
                approve_label="Send ONE exact request",
            )
        except (ValueError, RegistryRejected):
            self.status.set("Invalid or expired model quote. Reconfigure model in Settings.")
            return
        if not approved or self._closed:
            self.status.set("Not sent. Owner approval declined.")
            return
        # Defensive review snapshot prevents changes during nested Tk modal.
        if (self.input.get("1.0", "end-1c") != content or
                self.mode.get() != name or
                self._offers.get(provider) is not offer or
                not self.allow_network.get() or
                not self.desktop._universal_model_live_capability):
            self.status.set("Request changed during review. Nothing sent.")
            return
        self.allow_network.set(False)
        self.input.delete("1.0", "end")
        self._append("You", content)
        self._busy = True
        self.send.configure(state="disabled")
        self.model_box.configure(state="disabled")
        self.status.set("Sending one request. No automatic retry.")
        gateway = UniversalGateway(
            registry, allow_network=True,
            budget=self.desktop._universal_model_budget,
        )
        self._request = (content, provider, offer)
        thread = threading.Thread(
            target=self._worker, args=(gateway, content, provider, estimate),
            daemon=True,
        )
        thread.start()
        self._after_id = self.after(80, self._poll)

    def _worker(self, gateway, question, provider, estimate):
        try:
            result = gateway.generate(
                question, provider=provider, input_estimate=256,
                max_output_tokens=256, ceiling_micro_usd=estimate,
                approve_request=True, allow_real_task=True,
            )
            self._queue.put(("ok", result))
        except SafeProviderHTTPError as error:
            self._queue.put(("http", error.category))
        except (ProviderError, RegistryRejected, BudgetExceeded,
                PermissionError, ValueError, OSError):
            self._queue.put(("error", None))
        except BaseException:
            self._queue.put(("error", None))

    def _poll(self):
        self._after_id = None
        if self._closed or self.desktop._closing:
            return
        try:
            kind, value = self._queue.get_nowait()
        except queue.Empty:
            self._after_id = self.after(80, self._poll)
            return
        self._busy = False
        self._request = None
        self.send.configure(state="normal")
        self.model_box.configure(state="readonly")
        if kind == "ok":
            reply = value["reply"]
            self._append(reply.provider + " / " + reply.model, reply.text)
            self.status.set("Response received. New requests require fresh approval. "
                            "Previous messages are NOT automatically shared.")
        elif kind == "http":
            hints = {
                "authentication": "API key rejected. Recheck locally.",
                "billing": "Provider billing or credits need attention.",
                "rate_limited": "Provider rate limit reached.",
                "model_or_endpoint": "Model ID unavailable. Check Settings.",
                "access_denied": "Provider account lacks model access.",
                "server_error": "Provider server error.",
            }
            self._append("VARYN", "Request failed: " + hints.get(
                value, "Provider refused this request. No automatic retry."))
            self.status.set("Request failed. No automatic retry.")
        else:
            self._append("VARYN", "Request failed or local session budget exhausted. "
                         "Check network, credentials, or model settings. No retry.")
            self.status.set("Request failed. No automatic retry.")

    def close(self):
        self._closed = True
        if self._after_id is not None:
            try:
                self.after_cancel(self._after_id)
            except tk.TclError:
                pass
            self._after_id = None
        self._offers.clear()
        self._request = None
